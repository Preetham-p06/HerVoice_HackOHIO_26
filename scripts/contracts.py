"""Generate a deterministic TypeScript model contract from FastAPI OpenAPI schemas."""

import json, os, sys, tempfile
from pathlib import Path

os.environ["APP_MODE"] = "demo"
os.environ["DATA_DIR"] = tempfile.mkdtemp(prefix="hervoice-contract-")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from services.api.main import app

schema = app.openapi()
models = schema["components"]["schemas"]


def ts(s):
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "enum" in s:
        return " | ".join(json.dumps(x) for x in s["enum"])
    if "anyOf" in s:
        return " | ".join(ts(x) for x in s["anyOf"])
    if s.get("type") == "array":
        return "(" + ts(s["items"]) + ")[]"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
        "object": "Record<string, unknown>",
    }.get(s.get("type"), "unknown")


lines = ["// Generated by scripts/contracts.py from FastAPI OpenAPI. Do not edit.", ""]
for name, s in sorted(models.items()):
    fields = s.get("properties", {})
    req = s.get("required", [])
    lines.append("export type " + name + " = {")
    for k, v in fields.items():
        lines.append(
            "  " + json.dumps(k) + ("" if k in req else "?") + ": " + ts(v) + ";"
        )
    lines.extend(["};", ""])
out = Path(__file__).resolve().parents[1] / "packages/api-client/models.ts"
out.write_text("\n".join(lines))
(Path(__file__).resolve().parents[1] / "packages/api-client/openapi.json").write_text(
    json.dumps(schema, indent=2, sort_keys=True) + "\n"
)
print(
    "Generated API input models and OpenAPI; dictionary response shapes remain runtime contracts."
)
